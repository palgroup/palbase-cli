// TestEmitTypeScriptRegistration_TreeAndQuoting locks the real recursive
// namespace tree + tsPropKey quoting rules:
//   - 3-segment ids nest two levels deep (rooms.id.get → rooms: { id: { get } })
//     instead of emitting an invalid dot-joined `rooms.id:` key (SyntaxError);
//   - kebab-case method segments are single-quoted ('delete-all');
//   - kebab-case error codes are single-quoted in the errors map;
//   - an error CODE of __proto__ is skipped with a loud comment (even quoted,
//     a literal '__proto__': key sets the prototype in a JS object literal);
//   - duplicate error codes dedupe first-wins with a skip comment.
func TestEmitTypeScriptRegistration_TreeAndQuoting(t *testing.T) {
	ops := []swiftOp{
		{operationID: "rooms.id.get", method: "POST", path: "/rooms/id/get", input: &swiftSchema{kind: "object"}},
		{operationID: "things.boom", method: "POST", path: "/things/boom", errors: []swiftErrorDef{
			// Parse order matters for the dedupe: dupA precedes dupB, so
			// dupA wins after the stable sort by code.
			{name: "dupA", code: "dup_code", status: 400},
			{name: "dupB", code: "dup_code", status: 400},
			{name: "protoHack", code: "__proto__", status: 400},
			{name: "roomLocked", code: "room-locked", status: 409},
		}},
		{operationID: "todos.delete-all", method: "POST", path: "/todos/delete-all"},
	}
	out := emitTypeScript(ops, tsGeneratedConfig{URL: "https://x.example.com", APIKey: "k", Branch: "main"})

	// 3-segment id → real nested tree, not a dot-joined `rooms.id:` key.
	must(t, out, "  rooms: {")
	must(t, out, "    id: {")
	must(t, out, "      get: { method: 'POST', path: '/rooms/id/get' },")
	if strings.Contains(out, "rooms.id:") {
		t.Errorf("dot-joined namespace key must not appear (SyntaxError in TS):\n%s", out)
	}

	// Kebab method segment quoted.
	must(t, out, "    'delete-all': { method: 'POST', path: '/todos/delete-all', input: 'none' },")

	// Errors map: kebab code quoted, dup_code first-wins (dupA), __proto__ and
	// the duplicate skipped with loud comments.
	must(t, out, "errors: { dup_code: (e) => new ThingsBoomDupAError(e), 'room-locked': (e) => new ThingsBoomRoomLockedError(e) },")
	must(t, out, `// codegen: skipped error code "__proto__"`)
	must(t, out, `// codegen: skipped duplicate error code "dup_code"`)
	if strings.Contains(out, "__proto__:") || strings.Contains(out, "'__proto__':") {
		t.Errorf("__proto__ must never appear as an object key:\n%s", out)
	}
	if strings.Contains(out, "ThingsBoomDupBError") {
		t.Errorf("duplicate error code must keep the FIRST definition (dupA), not dupB:\n%s", out)
	}
}

// TestEmitTypeScriptGolden compares the full emitTypeScript output byte-for-byte
// against testdata/palbe_gen.golden.ts. Run with UPDATE_GOLDEN=1 to regenerate.
func TestEmitTypeScriptGolden(t *testing.T) {
	ops, err := parseOpenAPIForSwift([]byte(tsFixtureOpenAPI))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	got := emitTypeScript(ops, tsFullCfg)

	goldenPath := "testdata/palbe_gen.golden.ts"
	if os.Getenv("UPDATE_GOLDEN") == "1" {
		if err := os.WriteFile(goldenPath, []byte(got), 0o644); err != nil {
			t.Fatalf("write golden: %v", err)
		}
		t.Logf("golden updated: %s", goldenPath)
		return
	}

	goldenBytes, err := os.ReadFile(goldenPath)
	if err != nil {
		t.Fatalf("read golden (run with UPDATE_GOLDEN=1 to create): %v", err)
	}
	want := string(goldenBytes)
	if got == want {
		return
	}
	// Print first differing line for diagnosis.
	gotLines := strings.Split(got, "\n")
	wantLines := strings.Split(want, "\n")
	for i := 0; i < len(gotLines) && i < len(wantLines); i++ {
		if gotLines[i] != wantLines[i] {
			start := i - 2
			if start < 0 {
				start = 0
			}
			end := i + 4
			if end > len(gotLines) {
				end = len(gotLines)
			}
			t.Errorf("golden mismatch at line %d:\n  got:  %q\n  want: %q\ncontext (got lines %d-):\n%s",
				i+1, gotLines[i], wantLines[i], start+1,
				strings.Join(gotLines[start:end], "\n"))
			return
		}
	}
	if len(gotLines) != len(wantLines) {
		t.Errorf("golden mismatch: got %d lines, want %d lines", len(gotLines), len(wantLines))
	}
}

