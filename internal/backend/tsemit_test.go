func TestEmitTypeScriptRegistration(t *testing.T) {
	ops, err := parseOpenAPIForSwift([]byte(tsFixtureOpenAPI))
	if err != nil {
		t.Fatalf("parse: %v", err)
	}

	out := emitTypeScript(ops, tsFullCfg)

	// --- Header (both lines are golden-contract-exact) ---
	must(t, out, "// AUTO-GENERATED by `palbase types --lang ts` — DO NOT EDIT.")
	must(t, out, "// Regenerate: palbase types   (or automatically via the predev/prebuild script)")

	// --- Imports ---
	must(t, out, "import type { BackendError, CallOptions } from 'palbe';")
	must(t, out, "import { __configure, __registerNamespaces } from 'palbe/internal';")

	// --- __configure block (full config with google oauth) ---
	must(t, out, "__configure({")
	must(t, out, "  url: 'https://abc12345m.dev.palbase.studio',")
	must(t, out, "  apiKey: 'pb_abc12345m_cXXXX',")
	must(t, out, "  branch: 'main',")
	must(t, out, "  oauth: {")
	must(t, out, "    google: { enabled: true, clientId: 'g-123' },")
	must(t, out, "  },")
	must(t, out, "});")

	// --- __registerNamespaces block ---
	must(t, out, "__registerNamespaces({")

	// getHello — FLAT operationId → root-level descriptor key. This is the
	// live wire shape (verb-prefixed single-segment ids); dropping it would
	// generate an empty SDK against every real backend.
	must(t, out, "  getHello: { method: 'GET', path: '/hello', input: 'none' },")

	// rooms.create — multi-line (has errors map, sorted by code)
	must(t, out, "  rooms: {")
	must(t, out, "    create: {")
	must(t, out, "      method: 'POST',")
	must(t, out, "      path: '/rooms/create',")
	must(t, out, "      errors: { room_full: (e) => new RoomsCreateRoomFullError(e), room_locked: (e) => new RoomsCreateRoomLockedError(e) },")
	must(t, out, "    },")
	must(t, out, "  },")

	// todos.get — single-line (no errors, no body, has path param)
	must(t, out, "  todos: {")
	must(t, out, "    get: { method: 'GET', path: '/todos/{id}', pathParams: ['id'], input: 'none' },")

	// todos.list — single-line (no errors, no body, has query)
	must(t, out, "    list: { method: 'GET', path: '/todos', input: 'query' },")
	must(t, out, "  },")

	must(t, out, "});")

	// --- Skip comments ---
	must(t, out, "// codegen: skipped reserved namespace \"auth\"")
	must(t, out, "// codegen: skipped reserved namespace \"toString\"")

	// Skip comments live at the TOP of the namespaces section: after the
	// __configure block, just above __registerNamespaces (golden contract).
	cfgIdx := strings.Index(out, "__configure({")
	skipIdx := strings.Index(out, `// codegen: skipped reserved namespace "auth"`)
	regIdx := strings.Index(out, "__registerNamespaces({")
	if cfgIdx == -1 || skipIdx == -1 || regIdx == -1 || cfgIdx > skipIdx || skipIdx > regIdx {
		t.Errorf("skip comments must sit between __configure and __registerNamespaces (cfg=%d skip=%d reg=%d)\n---\n%s",
			cfgIdx, skipIdx, regIdx, out)
	}

	// auth and toString must NOT appear as namespace keys in the registration block.
	// Note: "oauth:" contains "auth:" as a substring, so we check for the indented key form.
	if strings.Contains(out, "  auth:") {
		t.Errorf("auth namespace key must not appear in registration block:\n%s", out)
	}
	if strings.Contains(out, "  toString:") {
		t.Errorf("toString namespace key must not appear in registration block:\n%s", out)
	}

	// Dump for external inspection (mirrors swiftgen_test's PALBE_GEN_OUT).
	if p := os.Getenv("PALBE_TS_GEN_OUT"); p != "" {
		if err := os.WriteFile(p, []byte(out), 0o644); err != nil {
			t.Fatalf("write %s: %v", p, err)
		}
	}
}

