package backend

// stack_bundle.go — building what a push ships.
//
// A stack takes an ARTIFACT: the controllers bundled into one module, plus the
// evaluated config. It does not build, and it cannot: bundling needs the
// project's own node_modules, and those live on the machine that wrote the code.
// So `palbase push` builds first, here, rather than shipping whatever a previous
// build happened to leave on disk — which is how somebody edits a controller,
// pushes, and deploys yesterday's code with today's commit message.
//
// The bundle is built with BUN, not esbuild, and that is not a preference: the
// runtime is Bun, so the code is built by the engine that will run it. Two
// bundlers means two opinions about how a decorator lowers, and the one that
// matters is the runtime's.
//
// DRIFT. The stack's own one-shot (`palsvc --push`) runs the same steps from
// runtime/scripts/bundle-controllers.sh in the palbase repository, so there are
// two implementations of one contract. What keeps them honest is the end of a
// push: the stack activates the artifact and REFUSES it unless the runtime is
// serving endpoints from it, so a bundle this file builds wrongly fails the push
// that built it rather than becoming a quiet 404 later.
import (
	"context"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// bundleEntryHeader is the first line of the generated entry. It is asserted by
// a golden test: the entry's SHAPE is the contract between this bundler and the
// runtime that loads its output.
const bundleEntryHeader = "// GENERATED by `palbase push` — do not edit, do not commit."

// buildStackArtifact bundles a project's controllers and evaluates its config.
//
// It writes .palbase/esm/controllers/controllers.js and .palbase/config.json,
// and removes both if any step refuses — a failed build must leave NOTHING to
// deploy, because the alternative is a push that ships the last good bundle
// while its author believes they shipped the new one.
func buildStackArtifact(ctx context.Context, dir string, w io.Writer) error {
	controllersDir := filepath.Join(dir, "controllers")
	if _, err := os.Stat(controllersDir); err != nil {
		return fmt.Errorf("%s does not exist — a backend is controllers/*.controller.ts", controllersDir)
	}
	if _, err := exec.LookPath("bun"); err != nil {
		return fmt.Errorf("bun is not installed, and it is what builds a backend for this runtime " +
			"(https://bun.sh). The stack runs Bun, so the bundle is built by the engine that will run it")
	}

	sources, err := controllerSources(controllersDir)
	if err != nil {
		return err
	}
	if len(sources) == 0 {
		return fmt.Errorf("no *.controller.ts under %s — nothing would answer", controllersDir)
	}

	// STAGE FIRST: each controller's RETURN TYPE becomes a response schema.
	//
	// A route's response schema is derived from the method's TypeScript return
	// type, and a type exists only in the source — so something has to read it
	// and write it into the bundle (`recordReturn`, the SDK's own mechanism).
	// Bundling the raw tree skips that, and the artifact then serves a
	// specification whose every 200 response is `{}`. Measured on 2026-08-16:
	// a real app failed to compile against its own project's generated client,
	// because every response had become an opaque value.
	//
	// The staging is the SAME code `palbase build` runs (devjs/return_types.js,
	// devjs/throw_analysis.js), which is the same code the cloud's deploy stager
	// runs. One implementation of a contract that has to hold in three places.
	staged, err := stageControllers(ctx, dir, w)
	if err != nil {
		return err
	}
	defer func() { _ = os.RemoveAll(staged) }()

	esmDir := filepath.Join(dir, ".palbase", "esm", "controllers")
	if err := os.MkdirAll(esmDir, 0o755); err != nil {
		return err
	}
	out := filepath.Join(esmDir, "controllers.js")
	configOut := filepath.Join(dir, ".palbase", "config.json")

	// Anything written from here on is removed when a gate refuses.
	built := false
	defer func() {
		if !built {
			_ = os.RemoveAll(filepath.Join(dir, ".palbase", "esm"))
			_ = os.Remove(configOut)
		}
	}()

	if err := os.WriteFile(filepath.Join(dir, ".palbase", "esm", "package.json"),
		[]byte(`{"type":"module"}`+"\n"), 0o644); err != nil {
		return err
	}

	stagedSources, err := controllerSources(staged)
	if err != nil {
		return err
	}
	entry := filepath.Join(staged, ".controllers-entry.ts")
	if err := os.WriteFile(entry, []byte(bundleEntry(dir, stagedSources)), 0o644); err != nil {
		return err
	}

	if err := run(ctx, dir, "bun", "build", entry, "--target=bun", "--format=esm", "--outfile="+out); err != nil {
		return fmt.Errorf("the bundle did not build: %w", err)
	}

	// A bundle carrying no controller is the silent-404 class: it would deploy,
	// activate, and answer nothing. Refused here, where its author is watching.
	count, err := output(ctx, dir, "bun", "-e", countControllers, out)
	if err != nil {
		return fmt.Errorf("the bundle could not be inspected: %w", err)
	}
	n, convErr := strconv.Atoi(strings.TrimSpace(count))
	if convErr != nil || n == 0 {
		return fmt.Errorf("the bundle carries ZERO controllers — nothing would answer")
	}
	fmt.Fprintf(w, "built %d controller file(s) → %d controller(s)\n", len(sources), n)

	if err := evaluateConfig(ctx, dir, configOut, w); err != nil {
		return err
	}

	// @Upload names a bucket that must EXIST. Both facts are in hand only here:
	// the bundle carries the routes, config.json carries the declared buckets.
	// A typo caught now names the bucket; caught later it is a 404 somebody
	// debugs from a phone.
	if err := run(ctx, dir, "bun", "-e", checkUploadBuckets, out, configOut); err != nil {
		return err
	}

	built = true
	return nil
}

// controllerSources lists a project's controllers in a stable order, so two
// builds of one tree produce the same bytes.
func controllerSources(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".controller.ts") {
			out = append(out, filepath.Join(dir, e.Name()))
		}
	}
	sort.Strings(out)
	return out, nil
}

// bundleEntry is the module the bundler starts from.
//
// It re-exports the SDK's request-scope hooks and the SDK namespace beside the
// controllers so the bundle and the runtime share ONE module instance: two
// instances would each get their own AsyncLocalStorage, and the request scope
// would silently not reach a handler.
//
// Controllers are imported for their SIDE EFFECT and never named — @Controller
// records the class as it decorates it, so a controller needs no export at all.
func bundleEntry(dir string, sources []string) string {
	var b strings.Builder
	b.WriteString(bundleEntryHeader + "\n")
	b.WriteString(`export { __runWithRuntime, __requestALS, __getRuntime } from "@palbase/backend";` + "\n")
	b.WriteString(`import * as SDK from "@palbase/backend"; export { SDK };` + "\n")
	for _, src := range sources {
		fmt.Fprintf(&b, "import %q;\n", src)
	}
	// The schema is optional: a project with no db/schema.ts still bundles, it
	// just has no typed `.tables` surface.
	if schema := filepath.Join(dir, "db", "schema.ts"); fileExists(schema) {
		fmt.Fprintf(&b, "import __schema from %q; export const schema = __schema;\n", schema)
	}
	// Read AFTER the imports above have run — ESM evaluates every import before
	// the module body, so every decorator has fired by this line.
	b.WriteString("export const controllers = SDK.getRegisteredControllers();\n")
	b.WriteString("export const getRegisteredControllers = SDK.getRegisteredControllers;\n")
	b.WriteString("export const jobs = []; export const webhooks = []; export const resources = [];\n")
	return b.String()
}

// evaluateConfig runs config/*.ts and writes what they declare.
//
// Evaluated at BUILD time and applied at deploy: the deploy side is Go and
// cannot execute TypeScript, and a runtime that evaluated them would apply a
// project's configuration on every start rather than once per push.
func evaluateConfig(ctx context.Context, dir, configOut string, w io.Writer) error {
	configDir := filepath.Join(dir, "config")
	if _, err := os.Stat(configDir); err != nil {
		_ = os.Remove(configOut)
		return nil
	}

	var b strings.Builder
	b.WriteString(bundleEntryHeader + "\n")
	for _, name := range []string{"storage", "flags", "notifications", "egress", "test-users"} {
		path := filepath.Join(configDir, name+".ts")
		if !fileExists(path) {
			continue
		}
		fmt.Fprintf(&b, "import __%s from %q; export const %s = __%s;\n",
			strings.ReplaceAll(name, "-", ""), path,
			strings.ReplaceAll(name, "-", ""), strings.ReplaceAll(name, "-", ""))
	}
	if authJSON := filepath.Join(configDir, "auth.json"); fileExists(authJSON) {
		fmt.Fprintf(&b, "import __auth from %q; export const auth = __auth;\n", authJSON)
	}

	entry := filepath.Join(configDir, ".config-entry.ts")
	if err := os.WriteFile(entry, []byte(b.String()), 0o644); err != nil {
		return err
	}
	defer func() { _ = os.Remove(entry) }()

	// A config that throws — an invalid flag key, a provider missing a required
	// field — fails the BUILD, where its author is watching, rather than the
	// deploy or a request.
	summary, err := output(ctx, dir, "bun", "-e", evaluateConfigScript, entry, configOut)
	if err != nil {
		return fmt.Errorf("config/ did not evaluate: %w", err)
	}
	fmt.Fprint(w, summary)
	return nil
}

func fileExists(path string) bool {
	_, err := os.Stat(path)
	return err == nil
}

func run(ctx context.Context, dir, name string, args ...string) error {
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Dir = dir
	blob, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s", strings.TrimSpace(trimBody(blob)))
	}
	return nil
}

func output(ctx context.Context, dir, name string, args ...string) (string, error) {
	cmd := exec.CommandContext(ctx, name, args...)
	cmd.Dir = dir
	var stderr strings.Builder
	cmd.Stderr = &stderr
	blob, err := cmd.Output()
	if err != nil {
		return "", fmt.Errorf("%s", strings.TrimSpace(trimBody([]byte(stderr.String()))))
	}
	return string(blob), nil
}

// countControllers reports how many classes in the bundle actually carry
// controller metadata — a count of exports would include anything.
const countControllers = `
const m = await import(process.argv[1]);
const withMeta = (m.controllers ?? []).filter(
  (c) => c && c[Symbol.for("palbase.backend.controllerMeta")] !== undefined,
);
console.log(withMeta.length);
`

const evaluateConfigScript = `
const mod = await import(process.argv[1]);
const out = {};
for (const [k, v] of Object.entries(mod)) if (v !== undefined) out[k] = v;
await Bun.write(process.argv[2], JSON.stringify(out, null, 2));
const kinds = Object.keys(out).filter((k) => k !== "default");
console.log("config: " + (kinds.length ? kinds.join(", ") : "(nothing declared)"));
`

// checkUploadBuckets reads the routes from the CLASS, under the SDK's own
// symbol — not from controllerMeta, which carries only __palbase and basePath.
// Guessing that shape produced a gate that quietly passed everything.
const checkUploadBuckets = `
const bundle = await import(process.argv[1]);
const listed = typeof bundle.getRegisteredControllers === "function"
  ? bundle.getRegisteredControllers() : [];
const ROUTES = Symbol.for("palbase.backend.routes");
const declared = new Set();
try {
  const cfg = JSON.parse(await Bun.file(process.argv[2]).text());
  for (const name of Object.keys(cfg?.storage?.buckets ?? {})) declared.add(name);
} catch { /* no config/ at all — every @Upload below is then undeclared */ }

const bad = [];
for (const c of listed) {
  for (const route of (c?.[ROUTES] ?? [])) {
    const bucket = route?.options?.uploadConfig?.bucket;
    if (bucket && !declared.has(bucket)) {
      bad.push(c.name + "." + (route.fnName ?? route.subpath) + ' → bucket "' + bucket + '"');
    }
  }
}
if (bad.length) {
  console.error(
    "@Upload names " + bad.length + " bucket(s) that config/storage.ts does not declare:\n  " +
    bad.join("\n  ") +
    "\nDeclared: " + (declared.size ? [...declared].join(", ") : "(none)") +
    "\nAdd the bucket to defineStorage({buckets}) or fix the name — storage will not create it on demand.",
  );
  process.exit(1);
}
`

// stageControllers writes a copy of the project's controllers with each route's
// return-type schema and inferred throws injected, and returns that directory.
//
// The project's own tree is never touched: the injection is machine-written code
// that belongs in a build, not in somebody's repository. Everything that is not
// a controller is copied verbatim, so relative imports (`../services`) still
// resolve from the staged tree.
func stageControllers(ctx context.Context, dir string, w io.Writer) (string, error) {
	if _, err := exec.LookPath("node"); err != nil {
		return "", fmt.Errorf("node is not installed, and it is what reads your controllers' return " +
			"types (https://nodejs.org). Without it every response in the deployed specification " +
			"would be untyped, and every generated client with it")
	}

	tools, err := os.MkdirTemp("", "palbase-stage-tools-*")
	if err != nil {
		return "", err
	}
	defer removeTemp(tools)
	if err := extractFS(buildCheckFS, "devjs", tools); err != nil {
		return "", fmt.Errorf("extract the stager: %w", err)
	}

	// Staged as a SIBLING of controllers/, which is what makes both kinds of
	// import resolve. Module resolution walks UP from the file being bundled, so
	// a staging directory in /tmp cannot see the project's node_modules and the
	// very first import — the SDK itself — fails; and one nested a level deeper
	// (.palbase/staged) turns every `../services` in a controller into a path
	// outside the project. The deploy stager stages a sibling for the same two
	// reasons.
	stageDir := filepath.Join(dir, ".palbase-staged-controllers")
	if err := os.RemoveAll(stageDir); err != nil {
		return "", err
	}
	if err := os.MkdirAll(stageDir, 0o755); err != nil {
		return "", err
	}

	script := filepath.Join(tools, "stage-for-push.js")
	if err := os.WriteFile(script, []byte(stageForPushScript), 0o644); err != nil {
		return "", err
	}

	cmd := exec.CommandContext(ctx, "node", script, filepath.Join(dir, "controllers"), stageDir, dir)
	cmd.Dir = dir
	// The analyzers need TypeScript's PARSER — the CLI's pinned copy first, then
	// the project's, because a project may be on TypeScript 7 (whose CommonJS
	// entry has no compiler API) or have none at all. `require` resolves from the
	// SCRIPT's directory, which is a temp dir with nothing in it, so the path has
	// to be said out loud.
	cmd.Env = append(os.Environ(), "NODE_PATH="+devNodePath(dir, w))
	blob, err := cmd.CombinedOutput()
	if err != nil {
		_ = os.RemoveAll(stageDir)
		return "", fmt.Errorf("%s", strings.TrimSpace(trimBody(blob)))
	}
	if summary := strings.TrimSpace(string(blob)); summary != "" {
		fmt.Fprintln(w, summary)
	}
	return stageDir, nil
}

// stageForPushScript drives the SHARED analyzers over one project.
//
// Written here rather than added to devjs/ because it is the only part that is
// specific to this command: `palbase build` stages into its own validation flow
// and the cloud's deploy stager into its bundler, and all three drive the same
// two modules underneath.
const stageForPushScript = `
const fs = require('fs');
const path = require('path');
const returnTypes = require('./return_types.js');
const throwAnalysis = require('./throw_analysis.js');

const [srcDir, stageDir, projectRoot] = process.argv.slice(2);

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

let injected = 0;
for (const file of walk(srcDir)) {
  const rel = path.relative(srcDir, file);
  const dest = path.join(stageDir, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  if (/\.controller\.(c?ts|tsx)$/i.test(path.basename(file))) {
    let out = returnTypes.injectReturnBindings(fs.readFileSync(file, 'utf8'), rel);
    out = throwAnalysis.injectThrowBindings(out, file, {
      readFile: (p) => { try { return fs.readFileSync(p, 'utf8'); } catch { return null; } },
      fileExists: (p) => fs.existsSync(p),
      projectRoot,
    });
    fs.writeFileSync(dest, out);
    injected += 1;
  } else {
    fs.copyFileSync(file, dest);
  }
}
console.log('typed ' + injected + ' controller file(s) from their return types');
`
