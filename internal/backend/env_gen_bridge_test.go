func TestEnvGenBridgeSkipsAnUnchangedFile(t *testing.T) {
	root, bundle, out := bridgeProject(t, fixtureSingleFileBackendPkg)
	request := func(flags ...string) map[string]any {
		return map[string]any{
			"bundle_path": bundle,
			"out_path":    out,
			"names":       wireNames(t, StackNames{Secrets: []string{}, Flags: flags, Buckets: []StackBucket{}, Roles: []string{}}),
		}
	}

	require.Empty(t, runEmbeddedBridge(t, "env-gen.js", root, request("new_ui")).Error)
	past := time.Now().Add(-2 * time.Hour).Truncate(time.Second)
	require.NoError(t, os.Chtimes(out, past, past))

	// AYNI İÇERİK: yazım yok, mtime tazelenmiyor (FR-001a).
	again := runEmbeddedBridge(t, "env-gen.js", root, request("new_ui"))
	require.Empty(t, again.Error)
	require.True(t, again.Unchanged, "aynı baytlar için köprü unchanged demeli")
	info, err := os.Stat(out)
	require.NoError(t, err)
	require.True(t, info.ModTime().Equal(past), "değişmeyen dosya yeniden yazıldı (mtime %s)", info.ModTime())

	// NEGATİF KONTROL: içerik değişince YAZILIR — "hiç yazma" bu testi geçemez.
	changed := runEmbeddedBridge(t, "env-gen.js", root, request("new_ui", "dark_mode"))
	require.Empty(t, changed.Error)
	require.False(t, changed.Unchanged)
	info, err = os.Stat(out)
	require.NoError(t, err)
	require.True(t, info.ModTime().After(past), "değişen içerik yazılmadı")
	require.Contains(t, readText(t, out), `"dark_mode": true;`)
}

