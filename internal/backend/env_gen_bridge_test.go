// bridgeProject lays out a project with the given @palbase/backend stand-in and
// one bundled schema — the shape the Go caller hands the bridge — and answers
// where the generated file goes. Its directory exists, as the Go caller makes
// sure it does.
func bridgeProject(t *testing.T, sdk string) (root, bundle, out string) {
	t.Helper()
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("node not on PATH")
	}
	root = t.TempDir()
	mustWrite(t, root, "node_modules/@palbase/backend/package.json",
		`{"name":"@palbase/backend","version":"0.0.0-test","main":"index.js"}`)
	mustWrite(t, root, "node_modules/@palbase/backend/index.js", sdk)
	mustWrite(t, root, "bundle/schema.js",
		`module.exports = { modules: [{ default: { name: "public", tables: {} } }], names: ["public"] };`+"\n")
	out = filepath.Join(root, filepath.FromSlash(EnvTypesPath()))
	require.NoError(t, os.MkdirAll(filepath.Dir(out), 0o755))
	return root, filepath.Join(root, "bundle", "schema.js"), out
}

type bridgeAnswer struct {
	Error     string `json:"error"`
	Unchanged bool   `json:"unchanged"`
}

// runEmbeddedBridge runs one devjs bridge the way the Go caller does: the script
// comes out of the CLI's embed.FS, NODE_PATH points at the project's
// node_modules, and the request arrives on stdin as JSON.
func runEmbeddedBridge(t *testing.T, script, root string, req map[string]any) bridgeAnswer {
	t.Helper()
	body, err := buildCheckFS.ReadFile("devjs/" + script)
	require.NoError(t, err)
	scriptPath := filepath.Join(t.TempDir(), script)
	require.NoError(t, os.WriteFile(scriptPath, body, 0o644))

	payload, err := json.Marshal(req)
	require.NoError(t, err)
	cmd := exec.Command("node", scriptPath)
	cmd.Dir = root
	cmd.Env = append(os.Environ(), "NODE_PATH="+filepath.Join(root, "node_modules"))
	cmd.Stdin = bytes.NewReader(payload)
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	stdout, err := cmd.Output()
	require.NoErrorf(t, err, "%s: %s", script, stderr.String())

	var answer bridgeAnswer
	require.NoErrorf(t, json.Unmarshal(stdout, &answer), "%s answered no JSON: %s", script, stdout)
	return answer
}

// wireNames is StackNames exactly as the CLI puts it on the wire. Marshalled from
// the Go type itself, so a renamed JSON tag goes red here instead of rendering
// an empty set in a customer's file.
func wireNames(t *testing.T, names StackNames) map[string]any {
	t.Helper()
	raw, err := json.Marshal(names)
	require.NoError(t, err)
	var wire map[string]any
	require.NoError(t, json.Unmarshal(raw, &wire))
	return wire
}

func readText(t *testing.T, path string) string {
	t.Helper()
	raw, err := os.ReadFile(path)
	require.NoError(t, err)
	return string(raw)
}

func TestEnvGenBridgeRendersTheStackBlockFromNames(t *testing.T) {
	root, bundle, out := bridgeProject(t, fixtureSingleFileBackendPkg)

	answer := runEmbeddedBridge(t, "env-gen.js", root, map[string]any{
		"bundle_path": bundle,
		"out_path":    out,
		"names": wireNames(t, StackNames{
			Secrets: []string{"STRIPE_KEY"},
			Flags:   []string{"new_ui"},
			Buckets: []StackBucket{{Name: "avatars", Variants: []string{"thumb"}}},
			Roles:   []string{"admin"},
		}),
	})
	require.Empty(t, answer.Error)
	require.False(t, answer.Unchanged)

	got := readText(t, out)
	for _, want := range []string{
		"// schemas: public",
		`"STRIPE_KEY": true;`,
		`"new_ui": true;`,
		`"avatars": true;`,
		`"admin": true;`, // roller de TELDEN geçiyor
		palbaseEnvBlockBegin,
		palbaseStackBlockEnd,
	} {
		require.Containsf(t, got, want, "tek dosya %q taşımıyor:\n%s", want, got)
	}
	require.True(t, strings.HasSuffix(got, "export {};\n"), "dosya bir modül olarak kalmalı (FR-005)")
}

