// fixtureSingleFileBackendPkg stands in for an @palbase/backend whose
// makeEnvDts renders BOTH blocks between the markers the CLI splices on. It is
// strict where the real renderer is typed: a set that arrives as anything but
// an array throws, so a bridge that forwarded the wrong shape fails here the
// way it would fail the compiler.
var fixtureSingleFileBackendPkg = strings.NewReplacer(
	"__ENV_BEGIN__", palbaseEnvBlockBegin,
	"__ENV_END__", palbaseEnvBlockEnd,
	"__STACK_BEGIN__", palbaseStackBlockBegin,
	"__STACK_END__", palbaseStackBlockEnd,
).Replace(`
'use strict';
function set(name, v) {
  if (!Array.isArray(v)) throw new Error('names.' + name + ' must be an array, got ' + JSON.stringify(v));
  return v.map((x) => (x && typeof x === 'object' ? x.name : x)).sort();
}
function members(list) {
  return list.length ? '\n' + list.map((n) => '    ' + JSON.stringify(n) + ': true;').join('\n') + '\n  ' : '';
}
function makeEnvDts(schemas, names) {
  const s = names === undefined
    ? { secrets: [], flags: [], buckets: [], roles: [] }
    : { secrets: set('secrets', names.secrets), flags: set('flags', names.flags),
        buckets: set('buckets', names.buckets), roles: set('roles', names.roles) };
  return '// AUTO-GENERATED by @palbase/backend — DO NOT EDIT.\n\n' +
    '__ENV_BEGIN__\n' +
    'declare module "@palbase/backend/env" {\n  // schemas: ' + schemas.map((d) => d.name).join(',') + '\n}\n' +
    '__ENV_END__\n\n' +
    '__STACK_BEGIN__\n' +
    'declare module "@palbase/backend/stack" {\n' +
    '  interface Secrets {' + members(s.secrets) + '}\n' +
    '  interface Flags {' + members(s.flags) + '}\n' +
    '  interface Buckets {' + members(s.buckets) + '}\n' +
    '  interface Roles {' + members(s.roles) + '}\n' +
    '}\n' +
    '__STACK_END__\n\nexport {};\n';
}
module.exports = { makeEnvDts };
`)

