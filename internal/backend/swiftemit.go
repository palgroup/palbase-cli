// swiftOAuthConfig is the provider-availability map fetched from palauth's
// public `/auth/oauth/providers` endpoint (Apple enabled flag, Google
// client_id/redirect_uri). Strictly secret-free — palauth's public endpoint
// never returns secrets. After the config cutover it is mapped onto the per-env
// Palbase-Info.plist's `oauth` block (via swiftOAuthToApps), the SOLE config
// source the iOS SDK reads; it is no longer serialized into a
// PalbaseGenerated.json. Nil means "fetch failed or no providers configured" —
// the iOS SDK's zero-arg `pb.auth.signInWithGoogle()` then throws (and
// `signInWithApple()` still works because Apple's flow needs no client_id).
type swiftOAuthConfig struct {
	Apple  *swiftOAuthApple  `json:"apple,omitempty"`
	Google *swiftOAuthGoogle `json:"google,omitempty"`
}

type swiftOAuthApple struct {
	Enabled bool `json:"enabled"`
}

type swiftOAuthGoogle struct {
	Enabled     bool   `json:"enabled"`
	ClientID    string `json:"client_id"`
	RedirectURI string `json:"redirect_uri"`
}

// emitSwift turns parsed operations into one PalbaseGenerated.swift.
//
// The Swift file is types + endpoint methods only; the runtime config
// (url / apiKey / oauth) ships separately as the per-env Palbase-Info.plist —
// a Bundle resource the Palbe SDK reads at startup (the SOLE config source
// after the JSON-config cutover). The split keeps customer apps off any
// cross-module reflection: typed methods compile against the SDK, the SDK loads
// its config from the bundle at startup.
func emitSwift(ops []swiftOp) string {
	// Reserved namespaces on `pb`: pb.auth.* / pb.analytics.* / pb.flags.* /
	// pb.realtime.* / pb.notifications.* / pb.perf.* are SDK-owned surfaces. An
	// endpoint whose top segment collides with one would shadow it (Swift
	// redeclaration / a confusing `pb.realtime.foo()` mixing SDK + generated),
	// so skip those endpoints and emit a visible comment so the developer knows
	// what was dropped. `perf` is the PalPerf facade (pb.perf.startTrace/...).
	reserved := map[string]bool{
		"auth":          true,
		"analytics":     true,
		"flags":         true,
		"realtime":      true,
		"notifications": true,
		"perf":          true,
	}
	var usable []swiftOp
	var swiftSkippedNS []string
	swiftSeenSkip := map[string]bool{}
	for _, op := range ops {
		segs := opSegments(op.operationID)
		if len(segs) > 0 && reserved[strings.ToLower(segs[0])] {
			ns := strings.ToLower(segs[0])
			if !swiftSeenSkip[ns] {
				swiftSeenSkip[ns] = true
				swiftSkippedNS = append(swiftSkippedNS, ns)
			}
			continue
		}
		usable = append(usable, op)
	}
	sort.Strings(swiftSkippedNS)

	var b strings.Builder
	b.WriteString("// Generated by `palbase mobile codegen ios` — DO NOT EDIT.\n")
	b.WriteString("// Source: the active Palbase mobile contract. Re-run after branch/schema changes.\n")
	b.WriteString("import Foundation\n")
	// Generated code now targets the PUBLIC typed-network surface — each op
	// emits a `PBEndpoint`/`PBVoidEndpoint` struct and the namespace method
	// forwards to `pb.call(<Op>Endpoint(...))`. `call`, `PBRequest`,
	// `PBMethod`, `PBPathSegment`, `PBEndpoint`/`PBVoidEndpoint`, `PBError`,
	// `BackendError`, and `AnyCodableValue` are all plain `public` on Palbe,
	// so a plain `import Palbe` suffices — the old `@_spi(Generated) _invoke`
	// seam is no longer referenced.
	b.WriteString("import Palbe\n\n")

	// Backend config (url/apiKey/oauth) is carried separately by the per-env
	// Palbase-Info.plist (codegen `--app`) and loaded by the Palbe SDK from
	// Bundle.main at startup — the SOLE config source. Keeps this Swift file
	// pure types + endpoint methods; no static-let config literal that the SDK
	// would otherwise need cross-module reflection to find.

	b.WriteString("// MARK: - Request / response types\n\n")
	b.WriteString(emitTypeTree(usable))

	b.WriteString("\n// MARK: - Namespaced calls (pb.*)\n\n")
	for _, ns := range swiftSkippedNS {
		b.WriteString("// codegen: skipped reserved namespace \"" + ns + "\" (SDK-owned)\n")
	}
	b.WriteString(emitNamespaceTree(usable))

	return b.String()
}

func swiftStringLiteral(s string) string {
	return strconv.Quote(s)
}

// --- Naming -----------------------------------------------------------------

func opSegments(opID string) []string {
	parts := strings.Split(opID, ".")
	var out []string
	for _, p := range parts {
		if p != "" {
			out = append(out, p)
		}
	}
	return out
}

func typeNameOf(s string) string { return sanitize(s, true) }
func identOf(s string) string    { return escapeKeyword(sanitize(s, false)) }

// typePrefix builds the PascalCase concatenation of all op-id segments,
// used as the BASE for top-level <Prefix>Request / <Prefix>Response /
// <Prefix>Error type names. Example: "rooms.create" → "RoomsCreate".
// Dots between segments are dropped — the user wants flat top-level
// struct names ("RoomsCreateRequest"), not nested
// "Rooms.Create.Input"-style enum trees.
func typePrefix(opID string) string {
	segs := opSegments(opID)
	parts := make([]string, len(segs))
	for i, s := range segs {
		parts[i] = typeNameOf(s)
	}
	return strings.Join(parts, "")
}

// requestTypeName / responseTypeName / errorEnumName are the three
// public top-level names per operation. Kept as small helpers so the
// emit + call sites agree without duplicating the suffix.
func requestTypeName(opID string) string  { return typePrefix(opID) + "Request" }
func responseTypeName(opID string) string { return typePrefix(opID) + "Response" }
func errorEnumName(opID string) string    { return typePrefix(opID) + "Error" }
func headersTypeName(opID string) string  { return typePrefix(opID) + "Headers" }
func queryTypeName(opID string) string    { return typePrefix(opID) + "Query" }

func sanitize(s string, firstUpper bool) string {
	var parts []string
	var cur strings.Builder
	for _, ch := range s {
		if (ch >= 'a' && ch <= 'z') || (ch >= 'A' && ch <= 'Z') || (ch >= '0' && ch <= '9') {
			cur.WriteRune(ch)
		} else if cur.Len() > 0 {
			parts = append(parts, cur.String())
			cur.Reset()
		}
	}
	if cur.Len() > 0 {
		parts = append(parts, cur.String())
	}
	if len(parts) == 0 {
		if firstUpper {
			return "Op"
		}
		return "op"
	}
	var res strings.Builder
	for i, p := range parts {
		if i == 0 && !firstUpper {
			res.WriteString(strings.ToLower(p[:1]) + p[1:])
		} else {
			res.WriteString(strings.ToUpper(p[:1]) + p[1:])
		}
	}
	out := res.String()
	if out[0] >= '0' && out[0] <= '9' {
		out = "_" + out
	}
	return out
}

var swiftKeywords = map[string]bool{
	"class": true, "struct": true, "enum": true, "func": true, "let": true, "var": true,
	"return": true, "if": true, "else": true, "for": true, "while": true, "switch": true,
	"case": true, "default": true, "import": true, "public": true, "private": true,
	"internal": true, "protocol": true, "extension": true, "self": true, "init": true,
	"deinit": true, "in": true, "where": true, "as": true, "is": true, "try": true,
	"throw": true, "throws": true, "async": true, "await": true, "nil": true, "true": true,
	"false": true, "guard": true, "defer": true, "do": true, "catch": true, "repeat": true,
	"operator": true, "associatedtype": true, "any": true,
}

func escapeKeyword(id string) string {
	if swiftKeywords[id] {
		return "`" + id + "`"
	}
	return id
}

func unbacktick(s string) string { return strings.ReplaceAll(s, "`", "") }

// snakeCaseRoundTrips reports whether the SDK's `.convertFromSnakeCase` decoder
// would map the wire key back to exactly `ident` (and `.convertToSnakeCase`
// would produce `key` from `ident`) — i.e. the coder strategy already bridges
// the two, so NO explicit CodingKey is needed (and emitting one would break
// decoding). It returns true when `key` is the plain snake_case form the
// strategy reconstructs `ident` from. Mirrors Foundation's documented
// `convertFromSnakeCase` (split on `_`, lowercase the first component, upper-
// case the first letter of each following component) including the leading/
// trailing-underscore passthrough, then checks the result equals `ident`.
func snakeCaseRoundTrips(ident, key string) bool {
	if ident == key {
		return true // already identical (e.g. `platform`, an escaped keyword)
	}
	if !strings.Contains(key, "_") {
		return false // no underscores → strategy leaves it as-is ≠ ident
	}
	// Preserve leading/trailing underscores exactly as Foundation does.
	lead := len(key) - len(strings.TrimLeft(key, "_"))
	trail := len(key) - len(strings.TrimRight(key, "_"))
	core := key[lead : len(key)-trail]
	if core == "" {
		return false
	}
	parts := strings.Split(core, "_")
	var b strings.Builder
	b.WriteString(key[:lead])
	for i, p := range parts {
		if p == "" {
			// Consecutive underscores: Foundation keeps an empty component,
			// which can't round-trip cleanly → force a mismatch (emit a key).
			return false
		}
		if i == 0 {
			b.WriteString(strings.ToLower(p))
		} else {
			b.WriteString(strings.ToUpper(p[:1]) + strings.ToLower(p[1:]))
		}
	}
	b.WriteString(key[len(key)-trail:])
	return b.String() == ident
}

func indent(d int) string { return strings.Repeat("    ", d) }

// --- Top-level Request / Response / Error types ----------------------------
//
// Each operation emits its own flat trio:
//   public struct RoomsCreateRequest:  Codable, Sendable { … }
//   public struct RoomsCreateResponse: Codable, Sendable { … }
//   public enum   RoomsCreateError:    GeneratedFailure     { … }
//
// Any nested object inside a request/response property is rendered as a
// `public struct <FieldName> { … }` **inside** the parent struct body
// (Swift's natural type-nesting), so the field references the short
// name directly. The struct emitter recurses depth-first, declaring
// the inner type at the same indent level as the field that uses it.
//
// Operations with no input emit no Request type; with no output emit
// no Response type. The Error enum is emitted for EVERY operation —
// `.other`-only when no errors were inferred — so the method's typed
// throws always names a concrete enum. The namespace methods below
// match the input/output shapes.

func emitTypeTree(ops []swiftOp) string {
	var lines []string
	for i := range ops {
		op := ops[i]
		emitted := false
		if op.input != nil {
			lines = append(lines, topLevelDeclLines(requestTypeName(op.operationID), *op.input)...)
			emitted = true
		}
		if op.output != nil {
			if emitted {
				lines = append(lines, "")
			}
			lines = append(lines, topLevelDeclLines(responseTypeName(op.operationID), *op.output)...)
			emitted = true
		} else if op.upload != nil {
			// An @Upload op ALWAYS surfaces a typed completion Response (the
			// uploadEndpointStructLines + namespace method reference
			// `<Op>Response` unconditionally). When the backend's OpenAPI
			// declares the @Upload 200 with no JSON body (responseSchema → nil,
			// so op.output is nil), we must STILL emit a concrete Response type
			// or the generated `typealias Response = <Op>Response` dangles and
			// the whole file fails to compile. Emit an empty Codable struct: it
			// decodes `{}` and tolerates extra fields, so a real completion body
			// (or none) both round-trip. Without this, a body-less @Upload op
			// silently breaks the entire generated SDK.
			if emitted {
				lines = append(lines, "")
			}
			lines = append(lines, "public nonisolated struct "+responseTypeName(op.operationID)+": Codable, Sendable {")
			lines = append(lines, "}")
			emitted = true
		}
		if op.headers != nil {
			if emitted {
				lines = append(lines, "")
			}
			lines = append(lines, headerStructLines(headersTypeName(op.operationID), *op.headers)...)
			emitted = true
		}
		if op.query != nil {
			if emitted {
				lines = append(lines, "")
			}
			lines = append(lines, queryStructLines(queryTypeName(op.operationID), *op.query)...)
			emitted = true
		}
		// EVERY op gets a PBError error enum — even with zero inferred
		// errors — so the wrapper's `throws(<Op>Error)` always has a
		// concrete type to name.
		if emitted {
			lines = append(lines, "")
		}
		lines = append(lines, topLevelErrorEnumLines(errorEnumName(op.operationID), op.errors)...)
		lines = append(lines, "")
		// Per-op endpoint struct (PBEndpoint when the op has a 200 body,
		// PBVoidEndpoint otherwise). It holds the call's inputs as stored
		// lets and computes a `pbRequest: PBRequest`; the namespace method
		// below forwards to `pb.call(<Op>Endpoint(...))`.
		lines = append(lines, endpointStructLines(op)...)
		lines = append(lines, "")
	}
	return strings.Join(lines, "\n")
}

// endpointStructName is the per-op endpoint struct name (e.g.
// "TodosShareEndpoint"). Kept as a helper so the emit + call sites agree.
func endpointStructName(opID string) string { return typePrefix(opID) + "Endpoint" }

// pathSegmentsExpr renders the op's wire path as a Swift `[PBPathSegment]`
// array literal: fixed segments become bare string literals (which the SDK's
// `ExpressibleByStringLiteral` reads as `.literal`), and `{name}` path-param
// segments become `.param(<ident>)` referencing the matching stored `let`.
// Empty segments (leading slash, trailing slash) are dropped so the array
// holds exactly the route's components. Mirrors the SDK's `renderPath`, which
// percent-encodes only the `.param` values.
func pathSegmentsExpr(path string) string {
	raw := strings.Split(path, "/")
	var segs []string
	for _, seg := range raw {
		if seg == "" {
			continue
		}
		if len(seg) >= 2 && seg[0] == '{' && seg[len(seg)-1] == '}' {
			name := seg[1 : len(seg)-1]
			if name == "" {
				continue
			}
			segs = append(segs, ".param("+identOf(name)+")")
		} else {
			segs = append(segs, swiftStringLiteral(seg))
		}
	}
	return "[" + strings.Join(segs, ", ") + "]"
}

// endpointStructLines emits one `public nonisolated struct <Op>Endpoint` that
// adopts `PBEndpoint` (op has a 200 body) or `PBVoidEndpoint` (no body). The
// struct stores the call's inputs as plain `let`s — path params as `String`,
// the request body as `<Op>Request`, the query as `<Op>Query`, headers as
// `<Op>Headers` — and computes a `var pbRequest: PBRequest` from them. The
// `Response`/`Failure` typealiases let `pb.call` infer the decoded success and
// typed error from the endpoint alone (no `as:`/`failing:` at the call site).
//
// `nonisolated` for the same Swift 6 + MainActor-default isolation reason as
// the DTO structs: PBEndpoint/PBVoidEndpoint require `Sendable`, and a wire
// value type is pure data.
func endpointStructLines(op swiftOp) []string {
	// An @Upload op adopts a DIFFERENT protocol (PBUploadEndpoint) and computes
	// an `authorizeRequest` (the POST pre-flight) instead of `pbRequest`. The
	// bytes go client→storage directly; this struct only carries the author
	// `@Body` input (+ path params) the br-pod needs to authorize + mint the
	// signed upload URL. Must be checked FIRST: an upload op may also have a 200
	// body (the completion Response), which would otherwise fall into PBEndpoint.
	if op.upload != nil {
		return uploadEndpointStructLines(op)
	}

	name := endpointStructName(op.operationID)
	hasBody := op.output != nil

	var lines []string
	if hasBody {
		lines = append(lines, "public nonisolated struct "+name+": PBEndpoint {")
		lines = append(lines, indent(1)+"public typealias Response = "+responseTypeName(op.operationID))
	} else {
		lines = append(lines, "public nonisolated struct "+name+": PBVoidEndpoint {")
	}
	lines = append(lines, indent(1)+"public typealias Failure = "+errorEnumName(op.operationID))

	// Stored inputs, in the same order the namespace method passes them:
	// path params first (in path order), then the request body, then the
	// query, then headers. Each is a plain `let` (the struct is created by
	// the namespace method with a memberwise init, no public init needed —
	// it's an internal-to-the-file forwarding value).
	for _, p := range op.pathParams {
		lines = append(lines, indent(1)+"let "+identOf(p)+": String")
	}
	if op.input != nil {
		lines = append(lines, indent(1)+"let input: "+requestTypeName(op.operationID))
	}
	if op.query != nil {
		lines = append(lines, indent(1)+"let query: "+queryTypeName(op.operationID))
	}
	if op.headers != nil {
		lines = append(lines, indent(1)+"let headers: "+headersTypeName(op.operationID))
	}

	// pbRequest: PBRequest(.<method>, [<segments>], body:?, query:?, headers:?)
	httpMethod := op.method
	if httpMethod == "" {
		httpMethod = "POST"
	}
	httpPath := op.path
	if httpPath == "" {
		httpPath = "/" + strings.ReplaceAll(op.operationID, ".", "/")
	}
	args := []string{"." + strings.ToLower(httpMethod), pathSegmentsExpr(httpPath)}
	if op.input != nil {
		args = append(args, "body: input")
	}
	if op.query != nil {
		args = append(args, "query: query")
	}
	if op.headers != nil {
		args = append(args, "headers: headers.asHeaderDict()")
	}
	lines = append(lines, indent(1)+"public var pbRequest: PBRequest { PBRequest("+strings.Join(args, ", ")+") }")
	lines = append(lines, "}")
	return lines
}

// uploadEndpointStructLines emits one `public nonisolated struct <Op>Endpoint`
// that adopts `PBUploadEndpoint` (op carries `x-palbase-upload`). Unlike the
// normal endpoint struct, the file bytes never touch the br-pod: the struct
// computes an `authorizeRequest` — the POST JSON pre-flight that carries the
// author `@Body` input so the br-pod can run its quota/ownership guard and mint
// a signed upload URL. The file source + progress are call-site arguments on
// `pb.call(_:file:onProgress:)`, NOT stored here, so one endpoint value can
// upload any file. `Response` is the typed completion (the @Upload method's
// return), `Failure` the typed error enum — both infer at the call site exactly
// like PBEndpoint.
//
// Stored inputs mirror endpointStructLines' order: path params first (in path
// order, each a `String`), then the author body as `<Op>Request`. Query/headers
// are not threaded onto an upload's pre-flight (the upload metadata travels in
// the body the runtime builds); they stay out of the generated struct.
func uploadEndpointStructLines(op swiftOp) []string {
	name := endpointStructName(op.operationID)

	var lines []string
	lines = append(lines, "public nonisolated struct "+name+": PBUploadEndpoint {")
	lines = append(lines, indent(1)+"public typealias Response = "+responseTypeName(op.operationID))
	lines = append(lines, indent(1)+"public typealias Failure = "+errorEnumName(op.operationID))

	for _, p := range op.pathParams {
		lines = append(lines, indent(1)+"let "+identOf(p)+": String")
	}
	if op.input != nil {
		lines = append(lines, indent(1)+"let input: "+requestTypeName(op.operationID))
	}

	// authorizeRequest: the pre-flight is always a POST (mint-signed-URL), with
	// the path rendered like any normal endpoint's pbRequest and the author body
	// carried as `body: input` when the op declares one.
	httpPath := op.path
	if httpPath == "" {
		httpPath = "/" + strings.ReplaceAll(op.operationID, ".", "/")
	}
	args := []string{".post", pathSegmentsExpr(httpPath)}
	if op.input != nil {
		args = append(args, "body: input")
	}
	lines = append(lines, indent(1)+"public var authorizeRequest: PBRequest { PBRequest("+strings.Join(args, ", ")+") }")
	lines = append(lines, "}")
	return lines
}

// topLevelDeclLines renders one top-level type for an operation side
// (request or response). Objects become `public struct <Name>`; an array of
// objects emits a named item struct `<Name>Item` (same field-emission as any
// response struct — snake_case→camelCase + CodingKeys) plus
// `public typealias <Name> = [<Name>Item]`, so a list endpoint surfaces a
// typed element instead of an opaque `[AnyCodableValue]`. Scalars and arrays
// of primitives (or unknown/empty items) fall back to
// `public typealias <Name> = <BareType>` so the call signature still reads
// typed (`[String]`, `[AnyCodableValue]`, …) and stays byte-identical to the
// pre-item-struct emitter.
func topLevelDeclLines(name string, s swiftSchema) []string {
	if s.kind == "object" {
		return structLines(name, s.props, 0)
	}
	if s.kind == "array" && s.elem != nil && s.elem.kind == "object" && len(s.elem.props) > 0 {
		itemName := name + "Item"
		lines := structLines(itemName, s.elem.props, 0)
		lines = append(lines, "")
		lines = append(lines, "public typealias "+name+" = ["+itemName+"]")
		return lines
	}
	return []string{"public typealias " + name + " = " + bareType(s)}
}

// headerStructLines emits the <Op>Headers struct (string-typed fields,
// like any request struct) PLUS an `asHeaderDict()` method that
// flattens it to the `[String: String]` the SDK seam sends on the wire.
// Header names keep their declared casing as dict keys (HTTP headers are
// case-insensitive; the server lowercases when matching). Optional
// fields are omitted from the dict when nil. Enum fields use rawValue.
func headerStructLines(name string, s swiftSchema) []string {
	lines := structLines(name, s.props, 0)
	// Drop the struct's closing brace so we can append the method inside.
	if len(lines) > 0 && strings.TrimSpace(lines[len(lines)-1]) == "}" {
		lines = lines[:len(lines)-1]
	}
	lines = append(lines, indent(1)+"public func asHeaderDict() -> [String: String] {")
	lines = append(lines, indent(2)+"var out: [String: String] = [:]")
	for _, p := range s.props {
		ident := identOf(p.name)
		key := swiftStringLiteral(p.name)
		optional := !p.required || p.schema.nullable
		// Value expression: enum → .rawValue, string → itself.
		valueExpr := ident
		if p.schema.kind == "enum" {
			valueExpr = ident + ".rawValue"
		}
		if optional {
			// `if let v = field { out[key] = <v|v.rawValue> }`
			if p.schema.kind == "enum" {
				lines = append(lines, indent(2)+"if let v = "+ident+" { out["+key+"] = v.rawValue }")
			} else {
				lines = append(lines, indent(2)+"if let v = "+ident+" { out["+key+"] = v }")
			}
		} else {
			lines = append(lines, indent(2)+"out["+key+"] = "+valueExpr)
		}
	}
	lines = append(lines, indent(2)+"return out")
	lines = append(lines, indent(1)+"}")
	lines = append(lines, "}")
	return lines
}

// queryStructLines emits the <Op>Query struct (typed Codable fields, like any
// request struct). It carries NO encoding logic of its own: the endpoint
// struct passes it as `PBRequest(query:)` and the SDK's `renderQuery` does the
// deterministic, sorted wire encoding (the `asQueryString()` method that used
// to live here moved INTO the SDK). The struct is plain Codable+Sendable so
// `renderQuery` can JSON-encode it.
func queryStructLines(name string, s swiftSchema) []string {
	return structLines(name, s.props, 0)
}

// topLevelErrorEnumLines renders one `public enum <Prefix>Error: PBError`
// block per operation — EVERY operation gets one, even with no inferred
// errors, so the wrapper's typed-throws signature always names a concrete
// enum. `PBError` is the SDK's typealias of `GeneratedFailure` (same protocol;
// new output uses the `PBError` spelling). `enumName` is the full top-level
// name (e.g. "RoomsCreateError") so customers reference it directly.
//
// Cases with a `data` payload carry the parsed Swift type as an
// associated value (declared inside the enum body so the case signature
// can reference it by short name; customers reference it as
// `<Enum>.<Name>Data`). Cases without are bare. Every enum closes with
// `case other(BackendError)` — the fallback for undeclared codes,
// non-server failures, and payloads that no longer decode.
//
// `init(_ backend:)` is the PBError (GeneratedFailure) requirement (non-failable):
// match `ServerFailure.code` against each declared wire code; decode the
// data payload via the SDK's tolerant `ServerFailure.decodeData` (a
// missing/renamed field degrades to `.other(backend)`, never traps);
// anything unmatched falls through to `.other(backend)`. The init is
// pure mapping — it NEVER fires the SDK's onError hook (the SDK fires
// that once at `_invokeCore` for every failure).
func topLevelErrorEnumLines(enumName string, errs []swiftErrorDef) []string {
	var lines []string
	// `nonisolated` for the same Swift 6 + MainActor-default isolation
	// reason as structLines — PBError requires a non-isolated
	// `init(_ backend:)`.
	lines = append(lines, "public nonisolated enum "+enumName+": PBError {")
	fd := 1

	// `other` is reserved for the fallback case; a declared error whose
	// name sanitizes to it (or to a previous case's ident) would emit an
	// uncompilable redeclaration — skip it with a visible comment (same
	// first-wins policy as structLines). Its wire code still surfaces at
	// runtime through `.other(backend)`.
	seenIdent := map[string]string{"other": "the other(BackendError) fallback"}
	var cases []swiftErrorDef
	for _, e := range errs {
		ident := unbacktick(identOf(e.name))
		if first, clash := seenIdent[ident]; clash {
			lines = append(lines, indent(fd)+"// codegen: skipped declared error "+
				swiftStringLiteral(e.name)+" — collides with "+first+
				" (both map to Swift `"+ident+"`); it surfaces as .other at runtime")
			continue
		}
		seenIdent[ident] = swiftStringLiteral(e.name)
		cases = append(cases, e)
	}

	// Per-case data payload structs / typealiases first so the case
	// declarations below can reference them by name (Swift requires
	// the type to be in scope at the case site).
	for _, e := range cases {
		if e.data == nil {
			continue
		}
		typeName := typeNameOf(e.name) + "Data"
		if e.data.kind == "object" {
			lines = append(lines, structLines(typeName, e.data.props, fd)...)
		} else {
			lines = append(lines, indent(fd)+"public typealias "+typeName+" = "+bareType(*e.data))
		}
	}

	// case declarations — declared cases first (already sorted by case
	// name in declaredErrors), then the `.other` fallback.
	for _, e := range cases {
		caseName := identOf(e.name)
		if e.data != nil {
			lines = append(lines, indent(fd)+"case "+caseName+"("+typeNameOf(e.name)+"Data)")
		} else {
			lines = append(lines, indent(fd)+"case "+caseName)
		}
	}
	lines = append(lines, indent(fd)+"case other(BackendError)")

	// init(_ backend:) — pure code-switch mapping (see doc comment).
	if len(cases) == 0 {
		lines = append(lines, indent(fd)+"public nonisolated init(_ backend: BackendError) { self = .other(backend) }")
		lines = append(lines, "}")
		return lines
	}
	lines = append(lines, indent(fd)+"public nonisolated init(_ backend: BackendError) {")
	lines = append(lines, indent(fd+1)+"guard case .server(let f) = backend else { self = .other(backend); return }")
	lines = append(lines, indent(fd+1)+"switch f.code {")
	for _, e := range cases {
		caseName := identOf(e.name)
		if e.data != nil {
			typeName := typeNameOf(e.name) + "Data"
			lines = append(lines, indent(fd+1)+"case "+swiftStringLiteral(e.code)+":")
			lines = append(lines, indent(fd+2)+"if let data = f.decodeData("+typeName+".self) { self = ."+caseName+"(data) } else { self = .other(backend) }")
		} else {
			lines = append(lines, indent(fd+1)+"case "+swiftStringLiteral(e.code)+": self = ."+caseName)
		}
	}
	lines = append(lines, indent(fd+1)+"default: self = .other(backend)")
	lines = append(lines, indent(fd+1)+"}")
	lines = append(lines, indent(fd)+"}")

	lines = append(lines, "}")
	return lines
}

func structLines(name string, props []swiftProp, depth int) []string {
	var lines []string
	// `nonisolated` is required for SWIFT_DEFAULT_ACTOR_ISOLATION=MainActor
	// targets (Xcode 16+ Swift 6). Without it, the Codable + Sendable
	// conformances inherit main-actor isolation and the SDK's generic
	// `_invoke<O: Decodable & Sendable>` constraint can't be satisfied:
	// "main actor-isolated conformance of <X> to 'Decodable' cannot
	// satisfy conformance requirement for a 'Sendable' type parameter".
	// Wire DTOs are pure data, so non-isolated is correct.
	lines = append(lines, indent(depth)+"public nonisolated struct "+name+": Codable, Sendable {")
	fd := depth + 1

	type field struct {
		ident, key, typ string
		optional        bool
	}
	var fields []field
	// Guard against identifier collision: two distinct wire keys can sanitize
	// to the SAME Swift ident (e.g. "device_id" and "deviceId" both → deviceId).
	// Emitting both would produce "Invalid redeclaration" for the property, the
	// init param, AND the CodingKeys case — uncompilable Swift. Keep the FIRST
	// key for each ident and skip later collisions, recording a visible comment
	// so the dropped wire key isn't silent. (A schema with both conventions for
	// one field is the usual cause — the generator can't know they're the same
	// field, so first-wins is the safe, deterministic choice; the nested types
	// of a skipped prop are also not emitted, avoiding duplicate type decls.)
	seenIdent := make(map[string]string, len(props))
	for _, p := range props {
		ident := identOf(p.name)
		if firstKey, clash := seenIdent[ident]; clash {
			lines = append(lines, indent(fd)+"// codegen: skipped duplicate key "+
				swiftStringLiteral(p.name)+" — collides with "+swiftStringLiteral(firstKey)+
				" (both map to Swift `"+unbacktick(ident)+"`)")
			continue
		}
		seenIdent[ident] = p.name
		optional := !p.required || p.schema.nullable
		typ, nested := fieldType(p.schema, p.name, fd)
		lines = append(lines, nested...)
		fields = append(fields, field{ident: ident, key: p.name, typ: typ, optional: optional})
	}
	for _, f := range fields {
		t := f.typ
		if f.optional {
			t += "?"
		}
		lines = append(lines, indent(fd)+"public let "+f.ident+": "+t)
	}
	// Memberwise init.
	var params []string
	for _, f := range fields {
		t := f.typ
		if f.optional {
			t += "? = nil"
		}
		params = append(params, f.ident+": "+t)
	}
	lines = append(lines, indent(fd)+"public init("+strings.Join(params, ", ")+") {")
	for _, f := range fields {
		lines = append(lines, indent(fd+1)+"self."+f.ident+" = "+f.ident)
	}
	lines = append(lines, indent(fd)+"}")
	// CodingKeys ONLY for the keys the SDK's coder strategy can't reconstruct.
	//
	// The SDK decodes responses with `.convertFromSnakeCase` and encodes
	// requests with `.convertToSnakeCase` (see palbackend-ios-src Codec.swift),
	// so a wire key that is the plain snake_case form of the camelCase ident
	// round-trips AUTOMATICALLY — emitting a `case x = "snake_key"` there is not
	// just redundant, it BREAKS decoding: `.convertFromSnakeCase` rewrites the
	// incoming key to camelCase BEFORE CodingKeys is consulted, so a literal
	// "snake_key" rawValue no longer matches and the field silently decodes nil.
	// We therefore emit a CodingKey only when the strategy can NOT recover the
	// ident from the wire key (e.g. a key with digits/uppercase the snake↔camel
	// round-trip doesn't reproduce). Most fields need no CodingKeys at all.
	needKeys := false
	for _, f := range fields {
		if !snakeCaseRoundTrips(unbacktick(f.ident), f.key) {
			needKeys = true
			break
		}
	}
	if needKeys {
		lines = append(lines, indent(fd)+"enum CodingKeys: String, CodingKey {")
		for _, f := range fields {
			if snakeCaseRoundTrips(unbacktick(f.ident), f.key) {
				lines = append(lines, indent(fd+1)+"case "+f.ident)
			} else {
				lines = append(lines, indent(fd+1)+"case "+f.ident+" = \""+f.key+"\"")
			}
		}
		lines = append(lines, indent(fd)+"}")
	}
	lines = append(lines, indent(depth)+"}")
	return lines
}

func fieldType(s swiftSchema, fieldName string, depth int) (string, []string) {
	switch s.kind {
	case "string":
		return "String", nil
	case "number":
		return "Double", nil
	case "integer":
		return "Int", nil
	case "boolean":
		return "Bool", nil
	case "any":
		return "AnyCodableValue", nil
	case "enum":
		typeName := typeNameOf(fieldName) + "Value"
		decl := []string{indent(depth) + "public nonisolated enum " + typeName + ": String, Codable, Sendable {"}
		for _, c := range s.enumVals {
			decl = append(decl, indent(depth+1)+"case "+identOf(c)+" = \""+c+"\"")
		}
		decl = append(decl, indent(depth)+"}")
		return typeName, decl
	case "array":
		elemType, nested := fieldType(*s.elem, fieldName+"Item", depth)
		return "[" + elemType + "]", nested
	case "object":
		typeName := typeNameOf(fieldName)
		return typeName, structLines(typeName, s.props, depth)
	}
	return "AnyCodableValue", nil
}

func bareType(s swiftSchema) string {
	switch s.kind {
	case "string":
		return "String"
	case "number":
		return "Double"
	case "integer":
		return "Int"
	case "boolean":
		return "Bool"
	case "enum":
		return "String"
	case "array":
		return "[" + bareType(*s.elem) + "]"
	}
	return "AnyCodableValue"
}

// --- Namespace tree (pb.<ns>.<op>) ------------------------------------------

type nsNode struct {
	path     []string
	children map[string]*nsNode
	methods  []swiftOp
}

func emitNamespaceTree(ops []swiftOp) string {
	root := &nsNode{children: map[string]*nsNode{}}
	for _, op := range ops {
		segs := opSegments(op.operationID)
		node := root
		for _, seg := range segs[:max0(len(segs)-1)] {
			if node.children[seg] == nil {
				node.children[seg] = &nsNode{path: append(append([]string{}, node.path...), seg), children: map[string]*nsNode{}}
			}
			node = node.children[seg]
		}
		node.methods = append(node.methods, op)
	}

	// BFS collect for deterministic output.
	var all []*nsNode
	queue := []*nsNode{root}
	for len(queue) > 0 {
		n := queue[0]
		queue = queue[1:]
		all = append(all, n)
		var keys []string
		for k := range n.children {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			queue = append(queue, n.children[k])
		}
	}

	var out strings.Builder
	for _, node := range all {
		out.WriteString(renderNSNode(node))
		out.WriteString("\n")
	}
	return out.String()
}

func nsTypeName(path []string) string {
	if len(path) == 0 {
		return "PalBackendClient"
	}
	parts := make([]string, len(path))
	for i, p := range path {
		parts[i] = typeNameOf(p)
	}
	return "PB" + strings.Join(parts, "") + "Namespace"
}

func renderNSNode(node *nsNode) string {
	isRoot := len(node.path) == 0
	var lines []string
	if isRoot {
		lines = append(lines, "public extension PalBackendClient {")
	} else {
		// nonisolated: app targets with MainActor default isolation would
		// otherwise pin the namespace (and every call on it) to the main
		// actor — pb.* must stay callable from any concurrency context.
		lines = append(lines, "public nonisolated struct "+nsTypeName(node.path)+": Sendable {")
		lines = append(lines, "    let _pb: PalBackendClient")
	}
	vis := "public "
	if isRoot {
		vis = "" // public extension members are implicitly public
	}
	pbRef := "_pb"
	if isRoot {
		pbRef = "self"
	}

	var keys []string
	for k := range node.children {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, seg := range keys {
		child := node.children[seg]
		ct := nsTypeName(child.path)
		lines = append(lines, indent(1)+vis+"nonisolated var "+identOf(seg)+": "+ct+" { "+ct+"(_pb: "+pbRef+") }")
	}

	for _, op := range node.methods {
		method := identOf(opSegments(op.operationID)[len(opSegments(op.operationID))-1])
		reqType := requestTypeName(op.operationID)
		resType := responseTypeName(op.operationID)
		errEnum := errorEnumName(op.operationID)
		throwsKw := "throws(" + errEnum + ")"

		// An @Upload op gets a DIFFERENT method shape: it takes `file:
		// PBFileSource` + the author `input:` (labelled, not `_`) + a trailing
		// `onProgress:` closure, and forwards both to the upload overload
		// `pb.call(_:file:onProgress:)`. The endpoint struct (PBUploadEndpoint)
		// holds only the author input/path params; the file + progress are
		// call-site args. Handled first, then `continue` past the normal path.
		if op.upload != nil {
			lines = append(lines, renderUploadMethodLines(op, method, reqType, resType, throwsKw, vis, pbRef)...)
			continue
		}

		// The method SIGNATURE is unchanged from the old emitter: path params
		// are LEADING `String` args (in path order), then the request body as
		// `_ input: <Op>Request`, then `query: <Op>Query`, then
		// `headers: <Op>Headers`. Only the BODY changed — it now collapses to
		// ONE forwarding line: `try await <pb>.call(<Op>Endpoint(<args>))`.
		// `pb.call` infers the decoded success type and typed error from the
		// endpoint's `Response`/`Failure` typealiases (no as:/failing:/where).
		var pathParamArgs []string
		for _, name := range op.pathParams {
			pathParamArgs = append(pathParamArgs, identOf(name)+": String")
		}
		queryParam := ""
		if op.query != nil {
			queryParam = "query: " + queryTypeName(op.operationID)
		}
		headerParam := ""
		if op.headers != nil {
			headerParam = "headers: " + headersTypeName(op.operationID)
		}
		// joinParams comma-joins the method parameters so we never emit a
		// dangling comma like `(, headers:)`. Path-param args always come
		// FIRST (in path order), then the request body, then query, then
		// headers.
		joinParams := func(parts ...string) string {
			var nonEmpty []string
			nonEmpty = append(nonEmpty, pathParamArgs...)
			for _, p := range parts {
				if p != "" {
					nonEmpty = append(nonEmpty, p)
				}
			}
			return strings.Join(nonEmpty, ", ")
		}

		// Endpoint-construction args mirror the struct's memberwise init in
		// declaration order (path params, then `input`, `query`, `headers`).
		// The labels equal the stored-property names: a path param `id` →
		// `id: id`; the body → `input: input`; etc.
		var endpointArgs []string
		for _, name := range op.pathParams {
			id := identOf(name)
			endpointArgs = append(endpointArgs, id+": "+id)
		}
		if op.input != nil {
			endpointArgs = append(endpointArgs, "input: input")
		}
		if op.query != nil {
			endpointArgs = append(endpointArgs, "query: query")
		}
		if op.headers != nil {
			endpointArgs = append(endpointArgs, "headers: headers")
		}
		callExpr := endpointStructName(op.operationID) + "(" + strings.Join(endpointArgs, ", ") + ")"

		// The request-body param is `_ input: <Op>Request` only when the op
		// declares a body; empty otherwise.
		inputParam := ""
		if op.input != nil {
			inputParam = "_ input: " + reqType
		}

		// Two shapes: a 200-body op returns its Response (@discardableResult);
		// a no-body op returns Void. Either way the body is one line.
		if op.output != nil {
			lines = append(lines, indent(1)+"@discardableResult")
			lines = append(lines, indent(1)+vis+"func "+method+"("+joinParams(inputParam, queryParam, headerParam)+") async "+throwsKw+" -> "+resType+" {")
			lines = append(lines, indent(2)+"return try await "+pbRef+".call("+callExpr+")")
		} else {
			lines = append(lines, indent(1)+vis+"func "+method+"("+joinParams(inputParam, queryParam, headerParam)+") async "+throwsKw+" {")
			lines = append(lines, indent(2)+"try await "+pbRef+".call("+callExpr+")")
		}
		lines = append(lines, indent(1)+"}")
	}

	lines = append(lines, "}")
	return strings.Join(lines, "\n") + "\n"
}

// renderUploadMethodLines emits the namespace method for an @Upload op. It
// forwards to the upload overload of `pb.call`:
//
//	func upload(file: PBFileSource, input: <Op>Request,
//	            onProgress: (@Sendable (BackendUploadProgress) -> Void)? = nil)
//	            async throws(<Op>Error) -> <Op>Response {
//	    try await <pb>.call(<Op>Endpoint(input: input), file: file, onProgress: onProgress)
//	}
//
// Path params (if any) are LEADING `String` args (path order) and thread into
// the endpoint's memberwise init exactly like a normal endpoint. The author
// `input:` is omitted entirely when the op declares no `@Body` schema. The file
// source + progress are call-site args (not stored on the endpoint), so the same
// generated endpoint value can upload any file.
func renderUploadMethodLines(op swiftOp, method, reqType, resType, throwsKw, vis, pbRef string) []string {
	// Method params: path params first, then file:, then input: (when present),
	// then the trailing onProgress: closure (defaulted to nil).
	var params []string
	for _, name := range op.pathParams {
		params = append(params, identOf(name)+": String")
	}
	params = append(params, "file: PBFileSource")
	if op.input != nil {
		params = append(params, "input: "+reqType)
	}
	params = append(params, "onProgress: (@Sendable (BackendUploadProgress) -> Void)? = nil")

	// Endpoint-construction args mirror uploadEndpointStructLines' stored order:
	// path params (label==name), then `input: input` when the op has a body.
	var endpointArgs []string
	for _, name := range op.pathParams {
		id := identOf(name)
		endpointArgs = append(endpointArgs, id+": "+id)
	}
	if op.input != nil {
		endpointArgs = append(endpointArgs, "input: input")
	}
	callExpr := endpointStructName(op.operationID) + "(" + strings.Join(endpointArgs, ", ") + ")"

	resultType := resType
	if op.output == nil {
		// An upload op without a declared completion body still returns the
		// generated Response type alias; guard defensively so the signature is
		// always well-formed (the runtime always emits a 200 for @Upload).
		resultType = responseTypeName(op.operationID)
	}

	var lines []string
	lines = append(lines, indent(1)+"@discardableResult")
	lines = append(lines, indent(1)+vis+"func "+method+"("+strings.Join(params, ", ")+") async "+throwsKw+" -> "+resultType+" {")
	lines = append(lines, indent(2)+"return try await "+pbRef+".call("+callExpr+", file: file, onProgress: onProgress)")
	lines = append(lines, indent(1)+"}")
	return lines
}

func max0(n int) int {
	if n < 0 {
		return 0
	}
	return n
}
